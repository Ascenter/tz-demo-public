  await fundSuccess(page, '50,000', '960,000')
  await goHome(page)
  await expectFirstFeedRow(page, 'Top up from M-Pesa', 'Top up', '+50,000')

  // S2: over the limit, then chip 100,000
  await page.getByTestId('quick-fund').click()
  await page.getByTestId('fund-mpesa').click()
  await typeAmount(page, 6_000_000)
  await expectRedLine(page, 'Over the limit of TZS 5,000,000 per top-up')
  await expect(page.getByTestId('amount-primary')).toBeDisabled()
  await clearAmount(page)
  await page.getByTestId('chip-100000').click()
  await fundSuccess(page, '100,000', '1,060,000')

  // S3: not enough on M-Pesa, change amount (kept) to 50,000
  await page.getByTestId('quick-fund').click()
  await page.getByTestId('fund-mpesa').click()
  await typeAmount(page, 600_000)
  await page.getByTestId('amount-primary').click()
  await page.getByTestId('sheet-confirm').click()
  await page.getByTestId('mpesa-send').click()
