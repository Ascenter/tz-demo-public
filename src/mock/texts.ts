export type TextKey = keyof typeof TEXTS

export function t(key: TextKey, params?: Record<string, string | number>): string {
  let s: string = TEXTS[key]
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  }
  return s
}
