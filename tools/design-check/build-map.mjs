// Builds design/screen-map.json: every ★ screen with a spec (manifest.json) + its setup (setups.mjs).
import { readFileSync, writeFileSync } from 'node:fs'
import { SETUPS } from './setups.mjs'

const ROOT = new URL('../../', import.meta.url).pathname
const m = JSON.parse(readFileSync(`${ROOT}design/figma-export/manifest.json`, 'utf8'))
const screens = []
const missing = []
for (const f of m.flows) {
  for (const s of f.screens) {
    if (!s.in_demo || !s.spec) continue
    const setup = SETUPS[s.id]
    if (!setup) {
      missing.push(`${s.id} ${s.name}`)
      continue
    }
    const { step, actions, mask, keyboard, deviations, ignore, known, settleMs } = setup
    screens.push({
      figmaId: s.id,
      name: s.name,
      flow: f.folder,
      png: `design/figma-export/${s.png_1x}`,
      spec: `design/figma-export/${s.spec}`,
      setup: { step, actions, ...(settleMs ? { settleMs } : {}) },
      mask: mask ?? [[0, 0, 402, 44]],
      ...(keyboard ? { keyboard: true } : {}),
      ...(deviations ? { deviations } : {}),
      ...(ignore ? { ignore } : {}),
      ...(known ? { known } : {}),
    })
  }
}
writeFileSync(
  `${ROOT}design/screen-map.json`,
  JSON.stringify({ _doc: 'Generated by `npm run design:map` from tools/design-check/setups.mjs + the Figma manifest. One entry per ★ screen with a spec.', screens }, null, 1) + '\n',
)
console.log(`screen-map.json: ${screens.length} screens${missing.length ? `; no setup yet for ${missing.length}:\n  ${missing.join('\n  ')}` : ''}`)
